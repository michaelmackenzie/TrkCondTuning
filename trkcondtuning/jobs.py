"""
Job specifications per kind (trig, offline, stage, timing) and the run helper.

Job directories: <wd>/jobs/<kind>/<config>/<sample>/<job>, <job> = f<NNN> (one input file of a
signal / cosmic sample) or g<NN> (background group), t00 (timing).
"""
from __future__ import annotations

import glob
import os
from typing import Dict, List, Optional, Sequence, Union

from . import fclgen, inputs
from .env import check_provenance, mu2e_env
from .runner import Job, JobResult, Runner
from .study import Config, Sample, Study

KINDS = ("trig", "offline", "stage", "timing")
MU2E = "mu2e --nthreads 1 --nschedules 1"


def _cfg(study: Study, config: Union[Config, str]) -> Config:
    if isinstance(config, Config):
        return config
    for c in study.configs():
        if c.name == config:
            return c
    raise KeyError(f"unknown configuration {config}")


def _check_redigi(config: Config) -> None:
    if not config.condition.redigi_ok:
        raise ValueError(
            f"condition {config.condition.name} has redigi_ok=False: re-digitizing the kept StrawGasSteps "
            "is only valid for conditions that lower the straw hit efficiency; it needs new digi samples")


def jobdir(wd: str, kind: str, config: str, sample: str, name: str) -> str:
    return os.path.join(wd, "jobs", kind, config, sample, name)


def job_dirs(wd: str, kind: str, config_name: str, sample_name: str) -> List[str]:
    """Existing job directories of a (kind, config, sample), sorted."""
    base = os.path.join(wd, "jobs", kind, config_name, sample_name)
    return sorted(d for d in glob.glob(os.path.join(base, "*")) if os.path.isdir(d))


def _script(wd: str, steps: List[str], keep: bool = True, cleanup: Sequence[str] = (), pre: Sequence[str] = ()) -> str:
    """cmd.sh: environment settings, then the steps (each must succeed)."""
    lines = ["#!/bin/bash",
             "# generated by tct; run in a shell with the muse environment (source setup.sh)",
             'cd "$(dirname "$0")" || exit 1',
             f'export MU2E_SEARCH_PATH="{wd}${{MU2E_SEARCH_PATH:+:$MU2E_SEARCH_PATH}}"',
             "export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 MKL_NUM_THREADS=1",
             "set -o pipefail"]
    lines += list(pre)
    lines += steps
    if cleanup and not keep:
        lines.append("rm -f " + " ".join(cleanup))
    return "\n".join(lines) + "\n"


def _split(sample: Sample, wd: str):
    """[(job name, [input files], nevents or None)]"""
    files = inputs.sample_files(sample, wd)
    if sample.role == "background":
        # all events of the files; sample.nevents, if set, caps each group job (tests only)
        return [(f"g{i:02d}", g, sample.nevents) for i, g in enumerate(inputs.groups(files, sample.ngroups))]
    return [(f"f{i:03d}", [f], sample.nevents) for i, f in enumerate(files)]


def _nopt(n: Optional[int]) -> str:
    return f" -n {n}" if n is not None else ""


def trig_jobs(study: Study, config: Union[Config, str], sample: Sample, wd: str) -> List[Job]:
    """Trigger-only jobs (AprHelixTruthAna -> ana.root): one per input file (signal / cosmic,
    first sample.nevents events), one per group (background, all events)."""
    config = _cfg(study, config)
    _check_redigi(config)
    fcl = fclgen.trig_fcl(study, config, sample, wd, "trig")
    out = []
    for name, files, nev in _split(sample, wd):
        cmd = _script(wd, [f"{MU2E} -c job.fcl -S inputs.txt{_nopt(nev)}"])
        out.append(Job("trig", config.name, sample.name, name, jobdir(wd, "trig", config.name, sample.name, name),
                       cmd, {"job.fcl": fcl}, files))
    return out


def offline_jobs(study: Study, config: Union[Config, str], sample: Sample, wd: str, keep_art: bool = False) -> List[Job]:
    """redigi (dig.art, triggerable events) -> Offline reco (mcs.art) -> EventNtuple (nts.root),
    one job per input file; dig.art / mcs.art are deleted after success unless keep_art."""
    config = _cfg(study, config)
    _check_redigi(config)
    if sample.role != "signal":
        raise ValueError("offline jobs are for signal samples")
    files_txt = {"redigi.fcl": fclgen.redigi_fcl(study, config, sample, wd),
                 "reco.fcl": fclgen.reco_fcl(study, config, wd),
                 "ntuple.fcl": fclgen.ntuple_fcl(study, config, wd)}
    out = []
    for name, files, nev in _split(sample, wd):
        steps = ['echo "=== step redigi"', f"{MU2E} -c redigi.fcl -S inputs.txt{_nopt(nev)} || exit 1",
                 'echo "=== step reco"', f"{MU2E} -c reco.fcl -s dig.art || exit 1",
                 'echo "=== step ntuple"', f"{MU2E} -c ntuple.fcl -s mcs.art -T nts.root || exit 1"]
        cmd = _script(wd, steps, keep_art, ["dig.art", "mcs.art"])
        out.append(Job("offline", config.name, sample.name, name, jobdir(wd, "offline", config.name, sample.name, name),
                       cmd, dict(files_txt), files, nsteps=3))
    return out


def stage_jobs(study: Study, config: Union[Config, str], sample: Sample, wd: str) -> List[Job]:
    """Trigger jobs with debug-level TC/HS/KS filters of the objective paths and per-event ArtReport
    markers (signal samples, same events as the offline jobs); also writes job.dump.fcl."""
    config = _cfg(study, config)
    _check_redigi(config)
    if sample.role != "signal":
        raise ValueError("stage jobs are for signal samples")
    fcl = fclgen.trig_fcl(study, config, sample, wd, "stage")
    out = []
    for name, files, nev in _split(sample, wd):
        cmd = _script(wd, ["fhicl-dump job.fcl > job.dump.fcl",
                           f"{MU2E} -c job.fcl -S inputs.txt{_nopt(nev)}"])
        out.append(Job("stage", config.name, sample.name, name, jobdir(wd, "stage", config.name, sample.name, name),
                       cmd, {"job.fcl": fcl}, files))
    return out


def timing_jobs(study: Study, config: Union[Config, str], sample: Sample, wd: str) -> List[Job]:
    """One TimeTracker job (timing.db) on the first study.timing_events events of a background sample."""
    config = _cfg(study, config)
    _check_redigi(config)
    if sample.role != "background":
        raise ValueError("timing jobs are for background samples")
    files = inputs.sample_files(sample, wd)
    fcl = fclgen.trig_fcl(study, config, sample, wd, "timing")
    cmd = _script(wd, [f"{MU2E} -c job.fcl -S inputs.txt -n {study.timing_events}"])
    return [Job("timing", config.name, sample.name, "t00", jobdir(wd, "timing", config.name, sample.name, "t00"),
                cmd, {"job.fcl": fcl}, files)]


def applicable_kinds(sample: Sample) -> List[str]:
    return {"signal": ["trig", "offline", "stage"], "background": ["trig", "timing"],
            "cosmic": ["trig"]}[sample.role]


def build_jobs(study: Study, configs: Sequence[Union[Config, str]], kinds: Sequence[str], wd: str,
               samples: Optional[Sequence[str]] = None, keep_art: bool = False) -> List[Job]:
    jobs: List[Job] = []
    if samples:   # names or Sample objects
        samples = [getattr(s, "name", s) for s in samples]
    for kind in kinds:
        for c in configs:
            c = _cfg(study, c)
            for s in study.samples:
                if samples and s.name not in samples:
                    continue
                if kind not in applicable_kinds(s):
                    continue
                if kind == "trig":
                    jobs += trig_jobs(study, c, s, wd)
                elif kind == "offline":
                    jobs += offline_jobs(study, c, s, wd, keep_art)
                elif kind == "stage":
                    jobs += stage_jobs(study, c, s, wd)
                elif kind == "timing":
                    jobs += timing_jobs(study, c, s, wd)
    return jobs


def run(study: Study, configs: Sequence[Union[Config, str]], kinds: Sequence[str], wd: str, runner: Runner,
        samples: Optional[Sequence[str]] = None, keep_art: bool = False, allow_mixed: bool = False) -> List[JobResult]:
    """Build and run the jobs of the given kinds for the configurations (all applicable samples,
    or those named in samples). The software provenance is checked against the last record of the
    work directory first (ProvenanceError if Offline / mu2e-trig-config / the build changed,
    unless allow_mixed). Raises RuntimeError after all jobs finished if any failed."""
    unknown = [k for k in kinds if k not in KINDS]
    if unknown:
        raise ValueError(f"unknown job kinds {unknown}; known: {KINDS}")
    if runner.env is None:
        runner.env = mu2e_env(workdir=wd)
    check_provenance(wd, runner.env, allow_mixed=allow_mixed, command="run " + ",".join(kinds), record=False)
    jobs = build_jobs(study, configs, kinds, wd, samples, keep_art)
    results = runner.submit(jobs)
    if not runner.dry_run:   # the shared work area can change under long runs
        check_provenance(wd, runner.env, allow_mixed=allow_mixed, command="run (end)", record=False)
    failed = [r for r in results if not r.ok and not runner.dry_run]
    if failed:
        raise RuntimeError(f"{len(failed)} of {len(jobs)} jobs failed:\n  " +
                           "\n  ".join(os.path.join(r.dir, "job.log") for r in failed))
    return results
